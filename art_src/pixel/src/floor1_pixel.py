def canvas(w, h=None, fill=None):
    return Image.new("RGBA", (w, h or w), fill)


def scene(img, shapes):
    d = ImageDraw.Draw(img)
    for color, pts in shapes:
        d.polygon(pts, fill="#" + color)
    return img


def atlas(frames, cols):
    w, h = frames[0].size
    out = canvas(w * cols, h * ((len(frames) + cols - 1) // cols))
    for i, frame in enumerate(frames):
        out.paste(frame, (i % cols * w, i // cols * h))
    return out


